export type AppErrorCode =
  | 'VALIDATION_ERROR'
  | 'UNAUTHENTICATED'
  | 'FORBIDDEN'
  | 'ROUTE_NOT_FOUND'
  | 'DEPENDENCY_UNAVAILABLE'
  | 'LISTING_NOT_FOUND'
  | 'LISTING_NOT_EDITABLE'
  | 'LISTING_INCOMPLETE'
  | 'LISTING_CONTACT_NOT_AVAILABLE'
  | 'LISTING_LOCATION_INVALID'
  | 'VEHICLE_MODEL_NOT_AVAILABLE'
  | 'VERIFICATION_REQUIRED'
  | 'VERIFICATION_FAILED'
  | 'REPORT_NOT_FOUND'
  | 'REPORT_ALREADY_REVIEWED'
  | 'REPORT_ALREADY_OPEN'
  | 'APPEAL_NOT_ALLOWED'
  | 'APPEAL_ALREADY_EXISTS'
  | 'APPEAL_NOT_FOUND'
  | 'APPEAL_ALREADY_REVIEWED'
  | 'REFERENCE_PARENT_NOT_FOUND'
  | 'RATE_LIMITED'
  | 'INTERNAL_ERROR'

export class AppError extends Error {
  constructor(
    readonly statusCode: number,
    readonly code: AppErrorCode,
    message: string,
  ) {
    super(message)
    this.name = 'AppError'
  }
}
